/**
 * 端 A · 令牌存取（**唯一权威点**）
 * ============================================================================
 *
 * 🛑 为什么单独一个文件，而不是让 session.ts 和 api/client.ts 各写各的
 * ---------------------------------------------------------------------------
 * 本轮落地时撞见一个**真实缺陷**（属本仓第 50 条同族）：
 *   · `services/session.ts` 写的是 `localStorage.setItem('dy.token', token)`；
 *   · `api/client.ts`   读的是 `localStorage.getItem('token')` —— **`'token'`**。
 * ⇒ 两者**键名不一致**，于是出站请求的 `Authorization` 头**永远为空**，
 *   所有需要鉴权的请求一律 401。
 *
 * 🛑 它为什么是"静默"的（这是本条最值得记住的一点）
 * ---------------------------------------------------------------------------
 *   · tsc **不报**：两个字符串都是合法字符串，类型上毫无关系；
 *   · 构建 **不报**：三端 `vite build` / `tsc --noEmit` 全过；
 *   · 门禁 **不报**：既有的判据查的是"端点是否属本端""角色是否被授予"，
 *     没有任何一条查"写进去的键与读出来的键是不是同一个"；
 *   · 单元测试 **不报**：本轮三端前端没有覆盖 localStorage 的测试。
 * ⇒ 只有**真跑起来、真发一次带鉴权的请求**才会暴露，而那时报出来的是 401，
 *   排查者会先去怀疑"账号权限配错了"，而不是"两个文件用了两个键名"。
 *
 * 🛑 修法（两层，缺一不可）
 * ---------------------------------------------------------------------------
 *   1. **把键名收敛到一个导出**（本文件）—— 两个使用方都引用它，
 *      物理上不存在"第二个键名"；
 *   2. **加一条门禁判据**（`tools/a-check.mjs` 的 `token-single-source`）——
 *      判"读/写形态必须经由本模块"，让"有人又写了一个裸键名字面量"这件事
 *      在构建期报红，而不是等真机 401。
 *   ⇒ 只做第 1 层仍然依赖"下一个人记得引用"；第 2 层才把这件事变成有牙齿的约束。
 *      （与第 50/51 条同一句教训：**靠人记住的约定等于没有约定**。）
 *
 * 🛑 与端 C 的键名差异**不是**本缺陷的一部分
 * ---------------------------------------------------------------------------
 * 端 C（小程序）用的是 `wx.getStorageSync('token')` —— **`'token'`**。
 * 三端的**存储介质本就不同**（小程序无 localStorage），键名不必强行统一；
 * 要统一的是"**同一端内**写与读必须是同一个键"。
 * 故本文件只解决端 A 内部的一致性，不去改动端 C。
 */

const TOKEN_KEY = 'dy.token';

/** 读取令牌。无令牌时返回空串（**不返回 null**，避免调用点各自处理两种空值）。 */
export function readToken(): string {
  try {
    return localStorage.getItem(TOKEN_KEY) ?? '';
  } catch {
    // 隐私模式 / 存储被禁用：返回空串，让请求以未鉴权形态发出，由服务端 401 兜底。
    return '';
  }
}

export function writeToken(token: string): void {
  localStorage.setItem(TOKEN_KEY, token);
}

export function clearToken(): void {
  localStorage.removeItem(TOKEN_KEY);
}

/** 供门禁与自证读取（键名本身仍只有本文件一处定义）。 */
export const TOKEN_STORAGE_KEY = TOKEN_KEY;