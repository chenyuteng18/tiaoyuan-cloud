// ============================================================================
// 端 B · 调理师 / 经络师 APP（原生 Android）—— 应用入口
// ============================================================================
//
// 🛑 这个类刻意**只做两件事**：环境自检 + 依赖装配
// ---------------------------------------------------------------------------
// 本仓代码组织纪律：入口只装配、零业务。Application 子类是最容易被塞进
// "初始化顺序玄学"的地方（先建数据库、再跑迁移、再预热缓存……），
// 一旦如此，任何一次启动期崩溃都会变成"顺序问题"而不是"缺陷"。
// 本端启动期只有两件事必须发生，且**顺序固定**：
//   1. 环境自检（AppEnv.assertConfigured）—— 基址缺失时立刻抛错（fail-closed）；
//   2. 依赖装配（Graph.init）—— 之后的任何页面都从这里取单例。
//
// 🛑 为什么环境自检放在装配之前
// ---------------------------------------------------------------------------
// 配错环境（基址为空 / 生产用明文 HTTP）是**部署错误**，不是运行错误。
// 让它先于装配暴露，能让"配错"在任何网络请求可能发生之前就终止 ——
// 否则用户会先看到登录页、输完账号密码才失败，而那时排查者会以为
// "后端连不上"，真实原因是**这个包根本没配基址**。
package com.diaoyuanyun.therapist

import android.app.Application
import com.diaoyuanyun.therapist.di.Graph
import com.diaoyuanyun.therapist.env.AppEnv

class DyTherapistApp : Application() {

    override fun onCreate() {
        super.onCreate()
        // ① 启动即自检环境：基址缺失 / 生产用明文 HTTP 时**立刻**抛错（fail-closed）。
        AppEnv.assertConfigured()
        // ② 依赖装配（唯一一处 new，见 di/Graph.kt 的注释）。
        Graph.init(this)
    }
}
