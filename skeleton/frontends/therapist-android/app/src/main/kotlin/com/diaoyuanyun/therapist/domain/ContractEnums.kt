package com.diaoyuanyun.therapist.domain

/**
 * 端 B · 契约具名枚举（**逐字转录 + 门禁核对**）
 * ============================================================================
 *
 * 为什么这个文件单独存在、且**只有两个枚举**
 * ---------------------------------------------------------------------------
 * 冻结契约 `components.schemas` 里**具名**的枚举只有这两个：
 *   · `Dimension`（7 值）
 *   · `AgeGroup`（8 值）
 * 其余在业务里用到的枚举（`ConsentAuthScope` / `BandWillingness` /
 * `ConsentDataSource` / 日报 `source` …）在契约里**全是内联声明，没有名字** ——
 * 它们的真相源是后端控制器的 record/参数类型，故那些值写在各自的使用点
 * （如 `ui/pages/IntakePage.kt` 的 `AUTH_SCOPES`），并附控制器出处说明。
 *
 * 🛑 手写即第二真相源 —— 所以必须给它配一条门禁
 * ---------------------------------------------------------------------------
 * 本文件是**手写的**（生成器目前只转录 operations，不转录 schemas）。
 * 手写枚举最坏的失效是**静默漂移**：契约新增一个维度、或改了某个分龄组的措辞，
 * 这里不会跟着变，而 Android 侧照旧提交旧值 ⇒ 服务端 400/1001，
 * 排查者会去查"是不是后端改了校验"，真实原因是**前端抄的是旧契约**。
 * ⇒ `frontends/tools/android-check.mjs` 的 `named-enum-verbatim` 判据
 *    **直接读契约 yaml**，逐值核对本文件的两个列表：
 *    少一个值、多一个值、改一个字，都会当场变红。
 *    同判据也核对 Web 端 `services/domain.ts` 的 `DIMENSIONS` / `AGE_GROUPS`，
 *    使四端在同一把尺子上。
 *
 * 🛑 一处如实登记的改进方向（不在本轮做，但必须写出来）
 * ---------------------------------------------------------------------------
 * 正解是让 `gen-endpoints.py` 把这两个具名枚举也**生成**（像 operations 一样），
 * 那样就没有"手写"这一步。之所以本轮没做：生成器要同时改四个 target 的产物，
 * 而 Web 三端此刻**各自在 `domain.ts` 里手写同一份值** ——
 * 一旦生成物也产出，就会出现"生成物 + 手写"两份，反而多一处分叉面。
 * 收敛路径（已登记在 README）：先把四端都改成读生成物，再删掉各自的手写副本。
 */
object ContractEnums {

    /**
     * 契约 `Dimension`（7 值，逐字）。
     * 用于 C1 题库筛选 与 C2 的 `dimension_scores` 顺序对齐。
     */
    val DIMENSION: List<String> = listOf(
        "体能精力",
        "面部气色肤质",
        "肩颈腰背筋骨",
        "睡眠质量",
        "记忆专注",
        "代谢体态消化",
        "情绪抗压与抵抗力",
    )

    /**
     * 契约 `AgeGroup`（8 档，逐字）。
     *
     * 🛑 注意取值里**含连字符与中文数字**（如 `男49以上` / `女43-49以上`）——
     *    "顺手规范化"成 `male_49_plus` 会让服务端拿不到匹配值，
     *    而客户端这一侧毫无症状。
     */
    val AGE_GROUP: List<String> = listOf(
        "男16-32", "男33-40", "男41-48", "男49以上",
        "女14-28", "女29-35", "女36-42", "女43-49以上",
    )

    /** 契约 `BaselineAssessmentRequest.dimension_scores` 的项数（= Dimension 的项数）。 */
    val DIMENSION_COUNT: Int get() = DIMENSION.size
}
